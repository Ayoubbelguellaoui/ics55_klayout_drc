"""Generate klayout/drc/RULE_INDEX.md from a real deck run.

Each row is one KLayout rule with its Calibre counterpart (when the foundry
deck has one) so reviewers can see coverage at a glance. Run manually after
deck changes:

    PYTHONPATH=src python3 tools/gen_rule_index.py
"""

from __future__ import annotations

import subprocess
import sys
import tempfile
from pathlib import Path

from ics55_klayout_drc.calibre_golden import normalize_rule_id, parse_deck
from ics55_klayout_drc.engine import find_klayout, run_drc
from ics55_klayout_drc.pdk import PACKAGE_ROOT, load_pdk_config

INDEX = PACKAGE_ROOT / "klayout" / "drc" / "RULE_INDEX.md"
CALIBRE_DECK = (
    PACKAGE_ROOT.parent
    / "icsprout55-pdk"
    / "pv"
    / "DRC"
    / "ICsprout_CalDRC_55LLULP1233_REV1_0_OS.drc"
)

DEFERRED_FAMILIES = (
    "SRCK (connectivity / soft-check)",
    "AAres / NWresAA / NWresSTI / HRP / POLYres (resistor families)",
    "AADUM / PODUM / *DUM (dummy-fill rules)",
    "LU (latch-up), MOM, ESD, CHIPEDGE, DEUPAD, PSUB, SL, CB, COVER",
    "T2M* / T2V* / T8M* / T8V* (non-default metal stacks)",
    "Recommended [R] variants and VIA*.EN.2a.2b.2c template splits",
)


def _empty_gds(klayout: str, tmp: Path) -> Path:
    gds = tmp / "empty.gds"
    script = tmp / "empty.rb"
    script.write_text(
        "ly = RBA::Layout.new\n"
        'ly.create_cell("TOP")\n'
        f"ly.write('{gds.as_posix()}')\n",
        encoding="utf-8",
    )
    subprocess.run([klayout, "-b", "-r", str(script)], check=True, capture_output=True)
    return gds


def _golden_ids() -> dict[str, str]:
    """normalized Calibre rule ID -> original underscore spelling."""
    if not CALIBRE_DECK.is_file():
        return {}
    return {normalize_rule_id(name): name for name in parse_deck(CALIBRE_DECK)}


def _family(rule: str) -> str:
    return rule.split(".", 1)[0]


def main() -> int:
    klayout = find_klayout()
    with tempfile.TemporaryDirectory() as tmp_name:
        tmp = Path(tmp_name)
        result = run_drc(
            _empty_gds(klayout, tmp),
            tmp / "out",
            load_pdk_config(),
            klayout=klayout,
        )
    rows = result.summary_data["rules"]
    golden = _golden_ids()

    lines = [
        "# ICS55 rule index (KLayout deck)"
        "",
        "Generated by `tools/gen_rule_index.py`; do not edit by hand.",
        "",
        "Default foundry option set: IO `1833`, `total_metal=6`, `top_metal=1`,",
        "`T4V2_T4M2=1`, recommended rules **off**.",
        "",
        f"KLayout rules checked on this stack: **{len(rows)}**.",
    ]
    if golden:
        matched = sum(1 for row in rows if row["rule"] in golden)
        lines.append(
            f"Calibre rule IDs in the foundry deck (expanded for this stack): "
            f"**{len(golden)}**; matched by this deck: **{matched}**."
        )
    lines += [
        "",
        "`Calibre ID` is the foundry spelling (`RULECHECK` name). `—` means the",
        "check exists only in the KLayout deck (geometric extras such as off-grid).",
        "",
        "## Rules",
        "",
        "| Rule | Layer | Class | Description | Calibre ID |",
        "|---|---|---|---|---|",
    ]
    for row in sorted(rows, key=lambda item: item["rule"]):
        calibre = golden.get(row["rule"], "—")
        description = (row.get("description") or "").replace("|", "/")
        lines.append(
            f"| `{row['rule']}` | {row.get('layer') or '—'} | {row.get('class') or 'error'} "
            f"| {description} | {calibre if calibre == '—' else '`' + calibre + '`'} |"
        )

    lines += [
        "",
        "## Deferred Calibre families",
        "",
        "These Calibre rule families are intentionally not implemented in v1.",
        "They are waived in `tests/expected/known_deltas.yml` so CI fails only on",
        "unexplained deltas.",
        "",
    ]
    lines += [f"- {item}" for item in DEFERRED_FAMILIES]
    lines.append("")

    INDEX.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {INDEX} ({len(rows)} rules)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
